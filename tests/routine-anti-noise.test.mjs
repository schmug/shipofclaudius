// ===================== PROMPT-INJECTION HARDENING (issue #3) =====================
test('a dedicated read-only relay fetches comments verbatim with a fresh nonce', async () => {
  const { calls } = await runScript({
    args: { number: 30, intent: 'x' }, inspect: { kind: 'pr', state: 'OPEN', labels: [], linkedIssues: [] },
  })
  const relay = byLabel(calls, 'comments-relay')[0]
  assert.ok(relay, 'a relay agent ran')
  assert.ok(/--json comments/.test(relay.prompt), 'relay fetches comments')
  assert.ok(/verbatim|byte-for-byte/i.test(relay.prompt), 'relay returns output verbatim')
  assert.ok(/nonce/i.test(relay.prompt), 'relay mints a nonce')
})

test('the dedupe prompt embeds comments as nonce-fenced UNTRUSTED DATA behind an anti-injection preamble', async () => {
  const { calls } = await runScript({
    args: { number: 30, intent: 'x' }, inspect: { kind: 'pr', state: 'OPEN', labels: [], linkedIssues: [] },
  })
  const d = byLabel(calls, 'dedupe')[0]
  assert.ok(d, 'a dedupe agent ran')
  assert.ok(d.prompt.includes('nonce-30-cafe'), 'fence carries the relay nonce')
  assert.ok(/UNTRUSTED[_ ]?(DATA|GH)/i.test(d.prompt), 'block labelled UNTRUSTED DATA')
  assert.ok(d.prompt.includes(COMMENT_INJECTION), 'hostile comment text present inside the fence as data')
  assert.ok(/never (obey|follow)/i.test(d.prompt), 'anti-injection preamble present')
  assert.ok(/injection/i.test(d.prompt), 'preamble names the injection threat')
})

test('the dedupe agent reads comments from the fence, not a live fetch', async () => {
  const { calls } = await runScript({
    args: { number: 30, intent: 'x' }, inspect: { kind: 'pr', state: 'OPEN', labels: [], linkedIssues: [] },
  })
  const d = byLabel(calls, 'dedupe')[0]
  assert.ok(/do NOT re-fetch/i.test(d.prompt), 'dedupe prompt tells the agent not to re-fetch the comments')
})

test('the signature footer is what makes a comment count — the prompt says human/unsigned comments never count', async () => {
  const { calls } = await runScript({
    args: { number: 30, intent: 'x' }, inspect: { kind: 'pr', state: 'OPEN', labels: [], linkedIssues: [] },
  })
  const d = byLabel(calls, 'dedupe')[0]
  assert.ok(d.prompt.includes(SIG), 'dedupe prompt carries the Claude Code signature')
  assert.ok(/human'?s comment|NEVER counts|never counts/i.test(d.prompt), 'unsigned/human comments explicitly excluded')
})

test('every subagent runs through a read-only agentType (Explore default + args.readonlyAgent override)', async () => {
  const base = { args: { number: 30, intent: 'x' }, inspect: { kind: 'pr', state: 'OPEN', labels: [], linkedIssues: [] } }
  const { calls } = await runScript(base)
  for (const a of calls.agents) assert.equal(a.opts.agentType, 'Explore', `${a.opts.label} read-only`)
  const { calls: c2 } = await runScript({ ...base, args: { ...base.args, readonlyAgent: 'gh-ro' } })
  for (const a of c2.agents) assert.equal(a.opts.agentType, 'gh-ro', `${a.opts.label} honors the override`)
})

test('the inspect agent is read-only and probes PR-then-issue', async () => {
  const { calls } = await runScript({ args: { number: 9 }, inspect: { kind: 'issue', state: 'OPEN', labels: [], linkedIssues: [] } })
  const ins = byLabel(calls, 'inspect')[0]
  assert.equal(ins.opts.agentType, 'Explore', 'inspect read-only')
  assert.ok(/gh pr view 9\b/.test(ins.prompt) && /gh issue view/.test(ins.prompt), 'inspect tries PR then issue')
  assert.ok(/closingIssuesReferences/.test(ins.prompt), 'inspect resolves linked issues from closingIssuesReferences (trusted, structured)')
})

// ===================== READ-ONLY / RETURN CONTRACT =====================
test('the workflow never asks any agent to comment/label/merge (fully read-only)', async () => {
  const { calls } = await runScript({
    args: { number: 30, intent: 'x' }, inspect: { kind: 'pr', state: 'OPEN', labels: [], linkedIssues: [] },
  })
  for (const a of calls.agents) {
    assert.ok(/do NOT (edit|comment|interpret)|read-only/i.test(a.prompt), `${a.opts.label} instructed read-only`)
  }
})

test('return shape carries the decision contract on every path', async () => {
  const { result } = await runScript({
    args: { number: 30, intent: 'x' }, inspect: { kind: 'pr', state: 'OPEN', labels: ['bug'], linkedIssues: [{ number: 5, labels: ['bug'] }] },
    dedupe: { duplicate: false, matchingExcerpt: '', rationale: 'none' },
  })
  for (const k of ['number', 'repo', 'kind', 'labels', 'linkedIssues', 'skip', 'reason', 'duplicateComment', 'duplicateChecked']) {
    assert.ok(k in result, `return carries '${k}'`)
  }
  assert.equal(result.kind, 'pr')
  assert.deepEqual(result.linkedIssues, [{ number: 5, labels: ['bug'] }], 'linked issues echoed for the caller')
})

