// Content-contract test for the session-end concern capture: the file-concerns
// process skill and the Stop hook that names it. Node built-ins only; zero token
// cost. Run: node tests/session-end-concerns.test.mjs
//
// The invariants here are the ones a well-meaning edit silently breaks. The hook
// prompt must stay phrased as a CONDITION — the harness wraps it as "has the
// following stopping condition been satisfied?", so an imperative is evaluated as
// though it were a condition and produces nonsense (observed: an imperative block
// reason produced "Understood, I'll do that IF I'm about to stop", i.e. the agent
// logged the rule instead of acting on it). It must keep its anti-nag clause,
// because every block replaces the session's closing message with hook-loop
// chatter. And it must keep naming the skill: the block `reason` is generated by
// the evaluator, not authored here, so without the name it has no procedure to
// point at.
import { readFile, mkdtemp } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import { execFileSync } from 'node:child_process'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import assert from 'node:assert/strict'

const ROOT = new URL('../', import.meta.url)
const read = (rel) => readFile(new URL(rel, ROOT), 'utf8')

const tests = []
const test = (name, fn) => tests.push([name, fn])

