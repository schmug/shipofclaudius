const hooksJson = JSON.parse(await read('hooks/hooks.json'))
const stopEntries = [].concat(hooksJson.hooks?.Stop || []).flatMap((g) => [].concat(g.hooks || []))

test('stop hook: one prompt-type entry with a timeout', () => {
  // Each entry costs a model call on every stop of every session.
  assert.equal(stopEntries.length, 1, 'exactly one Stop entry')
  // The agent type also runs on Stop and has tools, but costs ~13-16s per evaluation
  // against ~2-4s, and its tools are denied by default in unattended "don't ask" mode —
  // which is exactly where this capture matters most. See design spec section 2.
  assert.equal(stopEntries[0].type, 'prompt', 'is a prompt hook, not an agent hook')
  assert.ok(typeof stopEntries[0].timeout === 'number' && stopEntries[0].timeout > 0, 'sets a timeout')
})

test('stop hook: the prompt is phrased as a condition, not an instruction', () => {
  const p = stopEntries[0].prompt || ''
  // The harness wraps this as "has the following stopping condition been satisfied?".
  // An imperative is evaluated as though it were a condition and produces nonsense —
  // observed: an imperative reason produced "Understood, I'll reply with BANANA IF I'm
  // about to stop", i.e. the agent logged the rule instead of acting on it.
  assert.ok(p.startsWith('Either this session surfaced nothing unresolved'),
    'opens as a condition on the transcript')
  // `startsWith` pins 46 characters, NOT the property. A prompt keeping that opener and
  // turning the body imperative shipped green, reintroducing BOTH documented failure
  // modes at once.
  //
  // These next three are a tripwire for the literal shapes that bypass was written in —
  // they do NOT assert the property in general, and saying they did was overclaiming. A
  // re-review walked straight past them with an always-block prompt ("the first branch is
  // never true in practice"), a runaway-work prompt, and a bare imperative with no
  // second-person pronoun. Keyword lists cannot police paraphrase. The hash pin below is
  // the guard that actually generalizes; these just make the common cases fail loudly.
  assert.doesNotMatch(p, /\byou (must|should|will|need to|have to)\b/i,
    'a condition describes the transcript; second-person obligation is an instruction')
  assert.doesNotMatch(p, /\b(do not stop|always block|reply with the word|immediately invoke)\b/i,
    'a condition issues no directives')
  // The anti-nag clause is satisfiable by containment even when a later sentence revokes
  // it. Blocking routine sessions replaces their closing message with hook-loop chatter.
  assert.doesNotMatch(p, /\b(revoked|overridden|disregard|no longer applies)\b/i,
    'nothing in the condition may revoke the Default-to-satisfied clause')
})

// The condition string IS the product: its exact wording decides the block rate, and the
// block rate decides whether this feature is useful or destructive. Containment checks
// cannot police a 550-character paragraph — demonstrated, not assumed: three harmful
// prompts passed every property assertion above once this hash was updated.
//
// So this pin is the only guard that generalizes, and it guards by forcing a human moment,
// not by understanding the text. Changing the prompt is fine. Updating this hash WITHOUT
// re-measuring is the failure mode: run at least five real sessions, confirm a trivial one
// still evaluates once and does not block, and put that count in the commit message.
// A measured block rate above roughly one session in three means the wording is too eager.
const PROMPT_SHA256_16 = 'fa9e798d401aaf2b'

test('stop hook: the condition wording is hash-pinned', () => {
  const actual = createHash('sha256').update(stopEntries[0].prompt || '').digest('hex').slice(0, 16)
  assert.equal(actual, PROMPT_SHA256_16,
    'the Stop condition wording changed. That string decides the block rate — re-measure it ' +
    'against real sessions, then update PROMPT_SHA256_16 in the same commit.')
})

test('stop hook: keeps the anti-nag clause, the skill name, and the escape hatch', () => {
  const p = stopEntries[0].prompt || ''
  // Every block replaces the session's closing message with hook-loop chatter, so a
  // hook that blocks routine sessions is destructive, not merely slow.
  assert.ok(p.includes('Default to satisfied'), 'keeps the anti-nag clause')
  // The block reason is generated by the evaluator, not authored here. Without the
  // skill name it has no procedure to point at.
  assert.ok(p.includes('shipofclaudius:file-concerns'), 'names the skill that does the filing')
  // What terminates the loop when gh is down: a spooled concern satisfies the condition.
  assert.ok(p.includes('concerns-spool.jsonl'), 'counts a spooled concern as satisfying it')
})

// #173 reproduction, demonstrated under a scratch $HOME rather than pasted from a manual run:
// a concern appended between the triage's read and its disposal of the live spool survives
// rotation (the fix) and is destroyed by truncation (the bug). Both runs execute for real —
// `writeFile(live, '')` is the exact effect of `: > ~/.claude/concerns-spool.jsonl`, and
// `rename(...)` is the exact effect of the `mv` this issue asks for.
test('spool drain: rotate survives a concurrent append; truncate-in-place destroys it', async () => {
  const { mkdtemp, appendFile, rename, readFile: readSpool, writeFile, rm } =
    await import('node:fs/promises')
  const { tmpdir } = await import('node:os')
  const { join } = await import('node:path')

  async function raceThenDispose(dispose) {
    const scratchHome = await mkdtemp(join(tmpdir(), 'concerns-spool-'))
    const live = join(scratchHome, 'concerns-spool.jsonl')
    await appendFile(live, JSON.stringify({ ts: 't0', concerns: ['seeded before triage'] }) + '\n')
    await readSpool(live, 'utf8') // triage's read of the spool, opening the race window
    // a concurrent session's failed `gh` call appends inside that window
    await appendFile(live, JSON.stringify({ ts: 't1', concerns: ['concurrent, mid-window'] }) + '\n')
    const survivorPath = await dispose(live, scratchHome)
    const survivingLines = (await readSpool(survivorPath, 'utf8').catch(() => '')).trim().split('\n').filter(Boolean)
    await rm(scratchHome, { recursive: true, force: true })
    return survivingLines
  }

  const truncateResult = await raceThenDispose(async (live) => {
    await writeFile(live, '') // `: > ~/.claude/concerns-spool.jsonl`
    return live
  })
  assert.equal(truncateResult.length, 0,
    'truncate-in-place destroys the concurrent append with no trace — this is the #173 bug')

  const rotateResult = await raceThenDispose(async (live, scratchHome) => {
    const rotated = join(scratchHome, 'concerns-spool.20260903T011619Z.jsonl')
    await rename(live, rotated) // mv ~/.claude/concerns-spool.jsonl ~/.claude/concerns-spool.<ts>.jsonl
    return rotated
  })
  assert.equal(rotateResult.length, 2, 'rotate preserves both lines, including the concurrent one')
  assert.ok(
    rotateResult.some((line) => JSON.parse(line).concerns[0] === 'concurrent, mid-window'),
    'the concern appended during the triage window is recoverable from the rotated file'
  )
})

